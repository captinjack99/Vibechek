/**
 * Folder bucket name for a single move. Prefers the server-computed
 * `relative_destination` and falls back to a
 * defensive local split for older sidecar versions. Returns the parent
 * folder of the file, not the file path itself.
 */
function folderForMove(move: PlannedMove, baseDir: string): string {
  // Strip filename → parent folder. Works for both POSIX and Windows seps.
  const stripFilename = (p: string) =>
    p.replace(/[/\\][^/\\]+$/, "") || p;

  const rel = move.relative_destination;
  if (rel && rel !== move.destination) {
    const folder = stripFilename(rel);
    // "." means the file lands directly in base_dir
    return folder === "." || folder === "" ? "(root)" : folder;
  }

  // Fallback path for older sidecar payloads / missing rel field
  const folder = stripFilename(move.destination);
  if (!baseDir) return folder;
  // Case-insensitive prefix match — Windows is case-insensitive but
  // startsWith() isn't. Normalize separators while we're at it.
  const normFolder = folder.replace(/\\/g, "/");
  const normBase = baseDir.replace(/\\/g, "/");
  if (normFolder.toLowerCase().startsWith(normBase.toLowerCase())) {
    const stripped = normFolder.slice(normBase.length).replace(/^\/+/, "");
    return stripped || "(root)";
  }
  return folder;
}

