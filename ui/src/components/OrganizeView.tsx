/**
 * Plan and execute a genre-folder reorganization.
 *
 * Flow:
 *   1. Pick a source — either an analysis.json on disk, or the tracks
 *      currently loaded in the library.
 *   2. Tweak min-genre-size / use-subgenres / target-root.
 *   3. Click "Preview" — UI shows the move plan grouped by destination.
 *   4. Click "Execute" — actually moves the files.
 */

import { useEffect, useMemo, useRef, useState } from "react";
import {
  FolderTree, FolderOpen, Play, Eye, AlertCircle, ArrowRight, FileJson,
  CheckCircle2, RotateCcw, Undo2, Loader2,
} from "lucide-react";
import { open as openDialog, save as saveDialog } from "@tauri-apps/plugin-dialog";

import {
  useConfigStore, useLibraryStore, useNotificationStore, useOperationStore, useUIStore,
} from "../stores";
import { rpc, isCancellation } from "../hooks/useSidecar";
import { revertJournal, pruneEmptyFolders } from "../api/rpc";
import type { PruneEmptyFoldersResponse } from "../api/methods";
import type { OrganizePlan, PlannedMove as GeneratedPlannedMove } from "../types";
import { TagBadge } from "./TagBadges";
import { ConfirmModal } from "./ConfirmModal";

// Local extension of the generated PlannedMove dataclass. The Python side now
// emits `relative_destination` but the generated TS type is
// regenerated by a separate codegen step we don't own here, so we declare it
// inline as optional and use it wherever it's present.
type PlannedMove = GeneratedPlannedMove & { relative_destination?: string };

/** Hard cap on min_genre_size. 500 covers all realistic libraries — anything
 * higher is the user typo'ing and ending up with everything in Other/. */
const MAX_MIN_GENRE_SIZE = 500;
/** Above this, show a soft warning but don't block — power users may want it. */
const MIN_GENRE_SIZE_WARN_AT = 100;
/** If fewer than this fraction of tracks have ml_genre, warn the user that
 * organize will route most of them to Unknown/. 0.5 == "less than half". */
const ML_GENRE_COVERAGE_WARN_THRESHOLD = 0.5;

type Source =
  | { kind: "in-memory" }
  | { kind: "file"; path: string }
  | null;

/** Result of a completed organize run, captured for the result panel. */
interface OrganizeResult {
  baseDir: string;
  planned: number;
  moved: number;
  errors: string[];
  /** path of the tag backup we created first, if any */
  backupPath: string | null;
  /** destination-folder → number of files moved into it */
  folderCounts: [string, number][];
  /** undo-journal path for this run (null if nothing moved / journal failed) */
  journalPath: string | null;
  /** folders this run emptied — candidates for pruning, nothing removed yet */
  emptiedDirs: string[];
}

export function OrganizeView() {
  const tracks = useLibraryStore((s) => s.tracks);
  const libraryPath = useLibraryStore((s) => s.libraryPath);
  const updateTrackPaths = useLibraryStore((s) => s.updateTrackPaths);

  const active = useOperationStore((s) => s.active);
  const begin = useOperationStore((s) => s.begin);
  const finish = useOperationStore((s) => s.finish);
  const fail = useOperationStore((s) => s.fail);
  const errorMsg = useOperationStore((s) => s.error);

  const plan = useOperationStore((s) => s.organizePlan);
  const setPlan = useOperationStore((s) => s.setOrganizePlan);

  const orgCfg = useConfigStore((s) => s.config.organization);
  const updateOrganization = useConfigStore((s) => s.updateOrganization);

  const notify = useNotificationStore((s) => s.notify);

  const [source, setSource] = useState<Source>(
    tracks.length > 0 ? { kind: "in-memory" } : null,
  );
  const [showConfirm, setShowConfirm] = useState(false);
  const [backupFirst, setBackupFirst] = useState(true);
  const [result, setResult] = useState<OrganizeResult | null>(null);
  // Local validation state for the target_root input. `validating` gates the
  // Preview button while we're waiting on the sidecar's writability probe.
  const [targetError, setTargetError] = useState<string | null>(null);
  const [targetWarnings, setTargetWarnings] = useState<string[]>([]);
  const [validatingTarget, setValidatingTarget] = useState(false);
  // Guards against double-clicking Execute and opening two confirm modals
  // before the first one's confirm callback finishes.
  const confirmingRef = useRef(false);
  // Capture the params used to build the current plan so we can show a
  // "stale" warning when the user edits config without re-previewing.
  const [planParams, setPlanParams] = useState<string | null>(null);

  const setViewMode = useUIStore((s) => s.setViewMode);

  // Fingerprint of the params that flow into plan_organization. Updates to
  // Cheap content fingerprint of the fields that actually drive the organize
  // plan: each track's path + ML genre + subgenre. Counting `tracks.length`
  // alone was insufficient — a track whose genre changed (e.g. a re-analyze
  // updated ML fields without changing the file count) would leave the
  // previewed plan looking valid while the executed moves silently diverge.
  // Since organize is a destructive, no-undo file move, the confirmed preview
  // MUST match what executes. Recomputed only when `tracks` identity changes
  // (setTracks / mergeAnalyzedTrack), so it's O(n) once per change, not per
  // render.
  const tracksFingerprint = useMemo(() => {
    if (source?.kind !== "in-memory") return "";
    let h = 0;
    for (const t of tracks) {
      const s = `${t.path}|${t.ml_analysis?.ml_genre ?? ""}|${t.ml_analysis?.ml_subgenre ?? ""}`;
      // djb2-ish rolling hash — cheap, order-sensitive, collision-resistant
      // enough to detect content drift between preview and execute.
      for (let i = 0; i < s.length; i++) {
        h = (h * 33 + s.charCodeAt(i)) | 0;
      }
    }
    return `${tracks.length}:${h}`;
  }, [tracks, source?.kind]);

  // any of these invalidate a previously-generated plan.
  const currentParamsKey = useMemo(() => {
    return JSON.stringify({
      use_subgenres: orgCfg.use_subgenres,
      min_genre_size: orgCfg.min_genre_size,
      target_root: orgCfg.target_root ?? null,
      source:
        source?.kind === "file"
          ? { kind: "file", path: source.path }
          : source?.kind === "in-memory"
            ? { kind: "in-memory", fingerprint: tracksFingerprint }
            : null,
    });
  }, [orgCfg.use_subgenres, orgCfg.min_genre_size, orgCfg.target_root, source, tracksFingerprint]);

  // Drop a stale plan as soon as the user changes any input that feeds into
  // it. Cleaner than showing a "this plan is stale" banner — the user
  // re-clicks Preview and sees fresh counts.
  useEffect(() => {
    if (plan && planParams && planParams !== currentParamsKey) {
      setPlan(null);
      setPlanParams(null);
    }
  }, [currentParamsKey, plan, planParams, setPlan]);

  // ML-genre coverage check — disables Execute when most tracks lack a genre.
  // Counts tracks in the currently-loaded library only; we can't
  // peek inside a file-source analysis.json without loading it.
  const mlCoverage = useMemo(() => {
    if (source?.kind !== "in-memory") return null;
    if (tracks.length === 0) return null;
    let withGenre = 0;
    for (const t of tracks) {
      if (t.ml_analysis?.ml_genre) withGenre++;
    }
    return {
      total: tracks.length,
      withGenre,
      fraction: withGenre / tracks.length,
    };
  }, [source, tracks]);

  const lowCoverageWarning = useMemo(() => {
    if (!mlCoverage) return null;
    if (mlCoverage.fraction >= ML_GENRE_COVERAGE_WARN_THRESHOLD) return null;
    const pct = Math.round(mlCoverage.fraction * 100);
    return (
      `Only ${mlCoverage.withGenre} of ${mlCoverage.total} tracks (${pct}%) have ML ` +
      `genre data. The rest will be routed to Unknown/. ` +
      `Run Analyze in the Library tab first for better results.`
    );
  }, [mlCoverage]);

  const handlePickAnalysisFile = async () => {
    const path = await openDialog({
      directory: false,
      multiple: false,
      filters: [{ name: "Analysis JSON", extensions: ["json"] }],
    });
    if (typeof path === "string") setSource({ kind: "file", path });
  };

  const handlePickTargetRoot = async () => {
    const path = await openDialog({ directory: true, multiple: false });
    if (typeof path === "string") {
      updateOrganization({ target_root: path });
      // Re-validate as soon as the picker returns. Folder picker always
      // returns an absolute path, so this mainly catches the cloud-sync
      // warning case + the same-as-source path check.
      validateTarget(path);
    }
  };

  // Pure client-side validation of `target_root`. Catches the common foot-
  // guns (relative path → silent landing in sidecar
  // CWD, same-as-source path, cloud-sync target). Full writability probing
  // is left to the sidecar's _plan_organization step — that's where the
  // mkdir would happen for real anyway, and any PermissionError surfaces
  // there with a useful filesystem error.
  const validateTarget = (value: string | null | undefined) => {
    const trimmed = (value ?? "").trim();
    if (!trimmed) {
      // Empty == "use default", which is the loaded library's own root (the
      // sidecar anchors there via library_path). Always valid.
      setTargetError(null);
      setTargetWarnings([]);
      return;
    }
    setValidatingTarget(true);
    try {
      const error = clientValidateTarget(trimmed);
      setTargetError(error);
      setTargetWarnings(error ? [] : detectTargetWarnings(trimmed, libraryPath));
    } finally {
      setValidatingTarget(false);
    }
  };

  const buildParams = () => {
    const base: Record<string, unknown> = {
      use_subgenres: orgCfg.use_subgenres,
      min_genre_size: orgCfg.min_genre_size,
      target_root: orgCfg.target_root,
      // The loaded library's root. With no target_root set, the sidecar anchors
      // the genre tree here instead of guessing from track paths — a guess that
      // lands one level too deep as soon as the library is already sorted.
      library_path: libraryPath,
    };
    if (source?.kind === "file") base.analysis_path = source.path;
    else if (source?.kind === "in-memory") base.analysis = { tracks };
    return base;
  };

  const handlePreview = async () => {
    if (!source) return;
    // Re-validate the target one more time before planning. The on-blur
    // validator covers normal flow, but a user can edit and immediately hit
    // Preview without triggering blur (Enter, keyboard nav, etc.).
    if (orgCfg.target_root && orgCfg.target_root.trim()) {
      const error = clientValidateTarget(orgCfg.target_root.trim());
      if (error) {
        setTargetError(error);
        setTargetWarnings([]);
        return;
      }
    }
    begin("organize");
    try {
      const result = await rpc<OrganizePlan>("plan_organization", buildParams());
      setPlan(result);
      setPlanParams(currentParamsKey);
      finish();
    } catch (e) {
      fail(e);
    }
  };

  const handleExecuteClick = () => {
    if (!plan || plan.moves.length === 0) return;
    // Guard: a double-click would otherwise open two confirm modals back to
    // back, each of which kicks off its own performExecute on confirm.
    if (confirmingRef.current || showConfirm) return;
    confirmingRef.current = true;
    setShowConfirm(true);
  };

  const closeConfirm = () => {
    setShowConfirm(false);
    confirmingRef.current = false;
  };

  const performExecute = async () => {
    closeConfirm();
    if (!plan) return;

    // Optionally back up tags first so the user has a restore path
    let backupPath: string | null = null;
    if (backupFirst) {
      const out = await saveDialog({
        defaultPath: "tags_backup_pre_organize.json",
        filters: [{ name: "Tag backup (JSON)", extensions: ["json"] }],
      });
      if (typeof out !== "string") {
        // User cancelled the OS save dialog. This is indistinguishable from
        // the "I changed my mind, don't organize" case, so be loud about it:
        // tell them organize did NOT run, and leave the plan intact so they
        // can re-click Execute (or uncheck "back up tags first").
        notify("Backup cancelled. Organize did not run.", { kind: "info" });
        return;
      }
      backupPath = out;
      const backupOpId = begin("backup");
      try {
        await rpc("backup_tags", { path: plan.base_dir, output_path: out, op_id: backupOpId });
        finish();
      } catch (e) {
        fail(e);
        return;
      }
    }

    // Capture the planned destinations before we mutate `plan`
    const capturedPlan = plan;

    const opId = begin("organize");
    try {
      const stats = await rpc<{
        planned: number; moved: number; errors: string[]; journal_path: string | null;
        moved_pairs?: string[][];
        cancelled?: boolean;
        /** Optional: an older sidecar doesn't send it. */
        emptied_dirs?: string[];
      }>(
        "organize",
        { ...buildParams(), dry_run: false, op_id: opId },
      );
      finish();

      // Build a destination-folder breakdown from the captured plan. Prefer
      // the server-computed `relative_destination` over local string-arithmetic
      // (which breaks on Windows case / sep mismatch). Falls back
      // to a defensive split if the field is missing from an older sidecar.
      const folderCounts = new Map<string, number>();
      for (const move of capturedPlan.moves) {
        const folder = folderForMove(move, capturedPlan.base_dir);
        folderCounts.set(folder, (folderCounts.get(folder) ?? 0) + 1);
      }

      // Sync the library store: each successful move means the on-disk path
      // changed. Without this, the next time the user clicks Show in Folder /
      // Play / Re-tag we'd FileNotFoundError against the old path.
      //
      // CRITICAL: map from the sidecar's ACTUAL moved pairs, never the plan —
      // (a) a cancelled/partly-failed run moved only a subset (mapping the
      // whole plan pointed unmoved tracks at phantom destinations), and (b)
      // the real destination can differ from the planned one (re-uniquified at
      // execute time to avoid clobbering an existing file). The plan fallback
      // only covers an older sidecar that doesn't send moved_pairs, and only
      // for clean, complete runs.
      const pathMap = new Map<string, string>();
      if (stats.moved_pairs) {
        for (const [src, dst] of stats.moved_pairs) {
          pathMap.set(src, dst);
        }
      } else if (!stats.cancelled && stats.errors.length === 0) {
        for (const move of capturedPlan.moves) {
          pathMap.set(move.source, move.destination);
        }
      }
      updateTrackPaths(pathMap);

      setResult({
        baseDir: capturedPlan.base_dir,
        planned: stats.planned,
        moved: stats.moved,
        errors: stats.errors,
        backupPath,
        folderCounts: [...folderCounts.entries()].sort((a, b) => b[1] - a[1]),
        journalPath: stats.journal_path ?? null,
        emptiedDirs: stats.emptied_dirs ?? [],
      });
      setPlan(null);
      setPlanParams(null);

      // Brief notification too, in case the user navigated away mid-op. A
      // cancelled run still moved some files and left an undo journal — say so
      // rather than claiming a clean success.
      notify(
        stats.cancelled
          ? `Organize cancelled — moved ${stats.moved} of ${stats.planned} before stopping. Undo is available.`
          : `Moved ${stats.moved} of ${stats.planned} files`,
        { kind: stats.cancelled || stats.errors.length > 0 ? "info" : "success" },
      );
    } catch (e) {
      fail(e);
    }
  };

  const handleOrganizeAnother = () => {
    setResult(null);
    setSource(tracks.length > 0 ? { kind: "in-memory" } : null);
  };

  // When we have a completed-run result, replace the whole view with a
  // recap so the user actually reads what changed.
  if (result) {
    return (
      <OrganizeResultPanel
        result={result}
        onViewLibrary={() => setViewMode("library")}
        onAnother={handleOrganizeAnother}
      />
    );
  }

  return (
    <div className="h-full flex flex-col">
      {/* Header */}
      <div className="flex items-center justify-between px-4 py-3 border-b border-white/5">
        <div>
          <h1 className="font-display font-semibold text-white">Organize</h1>
          <p className="text-xs text-white/40 truncate max-w-md">
            {plan ? plan.base_dir : "no plan yet"}
          </p>
        </div>
        <div className="flex items-center gap-2">
          {plan && (
            <button
              className="btn-primary"
              onClick={handleExecuteClick}
              // showConfirm guard prevents a double-click from opening two
              // confirm modals before the first has shown its dialog.
              disabled={active !== null || plan.moves.length === 0 || showConfirm}
            >
              <Play className="w-4 h-4" />
              Execute ({plan.moves.length} moves)
            </button>
          )}
        </div>
      </div>

      {errorMsg && (
        <div className="m-4 panel-pad text-sm text-accent-red flex gap-2">
          <AlertCircle className="w-4 h-4 flex-none mt-0.5" />
          <div className="break-words">{errorMsg}</div>
        </div>
      )}

      <div className="flex-1 overflow-auto px-4 py-4">
        {/* Source picker */}
        <Section title="Source" subtitle="Where do the ML genre labels come from?">
          <SourcePicker
            source={source}
            inMemoryAvailable={tracks.length}
            onUseInMemory={() => setSource({ kind: "in-memory" })}
            onPickFile={handlePickAnalysisFile}
          />
        </Section>

        {/* ML-genre coverage warning — fast scan / partial analysis would
            otherwise quietly route everything into Unknown/. */}
        {lowCoverageWarning && (
          <div className="mb-4 panel-pad text-sm text-accent-yellow flex gap-2">
            <AlertCircle className="w-4 h-4 flex-none mt-0.5" />
            <div>{lowCoverageWarning}</div>
          </div>
        )}

        {/* Rules */}
        <Section title="Rules" subtitle="How the folder tree looks">
          <div className="grid grid-cols-2 gap-4">
            <div>
              <div className="label">Min tracks per genre folder</div>
              <input
                type="number"
                min={1}
                max={MAX_MIN_GENRE_SIZE}
                className="input w-24"
                title={`1–${MAX_MIN_GENRE_SIZE}. Higher values send more genres to Other/.`}
                value={orgCfg.min_genre_size}
                onChange={(e) => {
                  // Clamp to a sane range. Without the upper cap, a typo
                  // like 100000 silently turns the whole library into Other/.
                  const raw = Number(e.target.value);
                  const clamped = Math.max(
                    1,
                    Math.min(MAX_MIN_GENRE_SIZE, Number.isFinite(raw) ? raw : 1),
                  );
                  updateOrganization({ min_genre_size: clamped });
                }}
              />
              <div className="text-xs text-white/40 mt-1">
                Rarer genres get bucketed into <code>Other/</code>. Max {MAX_MIN_GENRE_SIZE}.
              </div>
              {orgCfg.min_genre_size >= MIN_GENRE_SIZE_WARN_AT && (
                <div className="text-xs text-accent-yellow mt-1">
                  High value — most genres will probably end up in <code>Other/</code>.
                </div>
              )}
            </div>
            <div>
              <div className="label">Subgenre subfolders</div>
              <label className="flex items-center gap-2 text-sm text-white/80 cursor-pointer">
                <input
                  type="checkbox"
                  checked={orgCfg.use_subgenres}
                  onChange={(e) => updateOrganization({ use_subgenres: e.target.checked })}
                  className="accent-accent"
                />
                Use them
              </label>
              <div className="text-xs text-white/40 mt-1">
                On: <code>House/Deep House/track.mp3</code>. Off: flat <code>House/</code>.
              </div>
            </div>
          </div>

          <div className="mt-4">
            <div className="label">Target root (override)</div>
            <div className="flex gap-2">
              <input
                type="text"
                className={`input flex-1 font-mono text-xs ${targetError ? "border-accent-red/60" : ""}`}
                value={orgCfg.target_root ?? ""}
                placeholder="(default: same parent as analyzed tracks)"
                onChange={(e) => {
                  // Clear stale validation feedback on each keystroke — the
                  // user is in the middle of fixing it. Re-validate on blur.
                  if (targetError) setTargetError(null);
                  if (targetWarnings.length > 0) setTargetWarnings([]);
                  updateOrganization({ target_root: e.target.value });
                }}
                onBlur={(e) => validateTarget(e.target.value)}
              />
              <button
                className="btn-ghost"
                onClick={handlePickTargetRoot}
                aria-label="Choose target root folder"
                title="Choose target root folder"
              >
                <FolderOpen className="w-4 h-4" />
              </button>
            </div>
            {targetError && (
              <div className="mt-1 text-xs text-accent-red flex gap-1.5">
                <AlertCircle className="w-3.5 h-3.5 flex-none mt-0.5" />
                <span>{targetError}</span>
              </div>
            )}
            {targetWarnings.map((w, i) => (
              <div key={i} className="mt-1 text-xs text-accent-yellow flex gap-1.5">
                <AlertCircle className="w-3.5 h-3.5 flex-none mt-0.5" />
                <span>{w}</span>
              </div>
            ))}
          </div>

          <button
            className="btn-primary mt-4"
            onClick={handlePreview}
            disabled={!source || active !== null || validatingTarget || !!targetError}
          >
            <Eye className="w-4 h-4" />
            {validatingTarget ? "Checking target..." : "Preview plan"}
          </button>
        </Section>

        {plan && <PlanPreview plan={plan} />}
      </div>

      <ConfirmModal
        open={showConfirm && !!plan}
        variant="danger"
        destructive
        icon={Play}
        title={plan ? `Move ${plan.moves.length} files?` : "Move files?"}
        message={
          plan && (
            <div className="space-y-2">
              <p>
                Vibechek will move <strong>{plan.moves.length}</strong> files into
                folders under{" "}
                <code className="font-mono text-xs text-white/90">{plan.base_dir}</code>.
              </p>
              <p className="text-xs text-white/60">
                First few moves:
              </p>
              <ul className="text-[11px] font-mono text-white/50 space-y-0.5 max-h-32 overflow-auto">
                {plan.moves.slice(0, 5).map((m) => {
                  // Widen to the extended PlannedMove that carries the optional
                  // `relative_destination` field — see import at top of file.
                  const ext = m as PlannedMove;
                  return (
                    <li key={m.source}>
                      {m.source.split(/[/\\]/).pop()} → {ext.relative_destination || m.destination}
                    </li>
                  );
                })}
                {plan.moves.length > 5 && <li>... and {plan.moves.length - 5} more</li>}
              </ul>
              <p className="text-accent-yellow">Files move immediately. You can undo
                this afterwards — from the result screen or "Recent operations".</p>
            </div>
          )
        }
        extra={
          <label className="flex items-start gap-2 cursor-pointer text-sm text-white/80">
            <input
              type="checkbox"
              checked={backupFirst}
              onChange={(e) => setBackupFirst(e.target.checked)}
              className="mt-0.5 accent-accent"
            />
            <div>
              <div>Back up all tags first <span className="text-xs text-accent-green">(recommended)</span></div>
              <div className="text-xs text-white/50">
                You'll be prompted for a save location. The backup lets you restore tags later if anything looks wrong.
              </div>
            </div>
          </label>
        }
        confirmLabel="Yes, move files"
        cancelLabel="Cancel"
        onConfirm={performExecute}
        onCancel={closeConfirm}
      />
    </div>
  );
}

