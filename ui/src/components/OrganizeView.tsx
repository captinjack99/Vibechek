/**
 * Result panel — shown after a successful organize. The user just performed a
 * destructive action across (potentially) thousands of files; they deserve a
 * real "here's what happened" screen, not just a toast that disappears.
 */
function OrganizeResultPanel({
  result,
  onViewLibrary,
  onAnother,
}: {
  result: OrganizeResult;
  onViewLibrary: () => void;
  onAnother: () => void;
}) {
  const success = result.errors.length === 0;
  const topFolders = result.folderCounts.slice(0, 10);
  const moreFolders = result.folderCounts.length - topFolders.length;

  const notify = useNotificationStore((s) => s.notify);
  const [undoing, setUndoing] = useState(false);
  const [undone, setUndone] = useState(false);
  // Per-file detail for a partial undo. The backend returns `error_messages`
  // (path + reason for each file it couldn't move back); the toast only
  // counted them. Only set when something didn't fully revert.
  const [undoResult, setUndoResult] = useState<{
    reverted: number;
    skipped: number;
    errorMessages: string[];
  } | null>(null);

  const [pruning, setPruning] = useState(false);
  const [showPruneConfirm, setShowPruneConfirm] = useState(false);
  const [pruneResult, setPruneResult] = useState<PruneEmptyFoldersResponse | null>(null);

  const handleUndo = async () => {
    if (!result.journalPath) return;
    // Register the revert as the global active op: without begin(), every
    // other view stayed enabled during the (potentially long) undo and each
    // click produced a confusing sidecar busy-rejection.
    if (useOperationStore.getState().active !== null) {
      notify("Another operation is running — wait for it to finish first.", { kind: "info" });
      return;
    }
    const ops = useOperationStore.getState();
    const opId = ops.begin("revert");
    setUndoing(true);
    try {
      const summary = await revertJournal({ journal_path: result.journalPath }, opId);
      ops.finish();
      setUndone(true);
      // Follow the files back in the in-memory library (reverse of the
      // post-execute updateTrackPaths above) so Preview / tag-apply keep
      // working without a re-scan.
      if (summary.reverted_pairs?.length) {
        const pathMap: Record<string, string> = {};
        for (const [current, restored] of summary.reverted_pairs) {
          pathMap[current] = restored;
        }
        useLibraryStore.getState().updateTrackPaths(pathMap);
      }
      const errorMessages = summary.error_messages ?? [];
      if (summary.skipped > 0 || errorMessages.length > 0) {
        setUndoResult({
          reverted: summary.reverted,
          skipped: summary.skipped,
          errorMessages,
        });
      }
      const parts = [`Restored ${summary.reverted}`];
      if (summary.skipped) parts.push(`skipped ${summary.skipped}`);
      if (summary.errors) parts.push(`${summary.errors} error(s)`);
      notify(`Undo complete — ${parts.join(", ")}`, {
        kind: summary.errors > 0 || summary.skipped > 0 ? "warning" : "success",
        detail:
          summary.skipped > 0 || summary.errors > 0
            ? "Some files couldn't be moved back — see the list below."
            : undefined,
      });
    } catch (e) {
      useOperationStore.getState().fail(e);
      if (!isCancellation(e)) {
        notify(
          typeof e === "object" && e !== null && "message" in e
            ? `Undo failed: ${String((e as { message: unknown }).message)}`
            : `Undo failed: ${String(e)}`,
          { kind: "info" },
        );
      }
    } finally {
      setUndoing(false);
    }
  };

  // --- Prune the folders this organize emptied -----------------------------
  // Deleting a directory is the most destructive thing this view does, so it
  // is never part of the organize itself: the user sees the count, confirms,
  // and only then does the sidecar remove anything (re-checking emptiness).
  const handlePrune = async () => {
    setShowPruneConfirm(false);
    if (!result.emptiedDirs.length) return;
    if (useOperationStore.getState().active !== null) {
      notify("Another operation is running — wait for it to finish first.", { kind: "info" });
      return;
    }
    setPruning(true);
    try {
      const summary = await pruneEmptyFolders({
        root: result.baseDir,
        dirs: result.emptiedDirs,
      });

      setPruneResult(summary);
      const kept = summary.skipped.length + summary.errors.length;
      notify(
        `Removed ${summary.removed.length} empty folder${summary.removed.length === 1 ? "" : "s"}` +
          (kept > 0 ? ` — ${kept} kept` : ""),
        {
          kind: summary.errors.length > 0 ? "warning" : "success",
          detail: kept > 0 ? "Folders that weren't empty are listed below." : undefined,
        },
      );
    } catch (e) {
      if (!isCancellation(e)) {
        notify(
          typeof e === "object" && e !== null && "message" in e
            ? `Couldn't remove folders: ${String((e as { message: unknown }).message)}`
            : `Couldn't remove folders: ${String(e)}`,
          { kind: "info" },
        );
      }
    } finally {
      setPruning(false);
    }
  };

  return (
    <div className="h-full overflow-auto">
      <div className="px-6 py-8 max-w-3xl mx-auto space-y-5">
        {/* Headline */}
        <div className="flex items-start gap-4">
          {success ? (
            <CheckCircle2 className="w-12 h-12 text-accent-green flex-none" />
          ) : (
            <AlertCircle className="w-12 h-12 text-accent-yellow flex-none" />
          )}
          <div className="flex-1">
            <h1 className="font-display font-semibold text-2xl text-white">
              {success ? "Library organized" : "Mostly done"}
            </h1>
            <p className="text-sm text-white/60 mt-1">
              Moved <strong className="text-white">{result.moved.toLocaleString()}</strong>{" "}
              of <strong className="text-white">{result.planned.toLocaleString()}</strong> files
              into <strong className="text-white">{result.folderCounts.length}</strong> folders.
            </p>
            <p className="text-xs text-white/40 font-mono mt-1 break-all">{result.baseDir}</p>
          </div>
        </div>

        {/* Summary stats */}
        <div className="grid grid-cols-3 gap-3">
          <Stat label="Moved" value={result.moved.toLocaleString()} accent="green" />
          <Stat
            label="Errors"
            value={result.errors.length.toLocaleString()}
            accent={result.errors.length > 0 ? "yellow" : "neutral"}
          />
          <Stat label="Destinations" value={result.folderCounts.length.toLocaleString()} accent="neutral" />
        </div>

        {/* Folder breakdown */}
        <div className="panel-pad">
          <div className="flex items-center gap-2 mb-3">
            <FolderTree className="w-4 h-4 text-accent" />
            <h2 className="font-medium text-white">Where files landed</h2>
          </div>
          <div className="space-y-1">
            {topFolders.map(([folder, count]) => {
              const pct = (count / Math.max(result.moved, 1)) * 100;
              return (
                <div key={folder} className="flex items-center gap-3 text-sm">
                  <div className="flex-1 min-w-0 truncate font-mono text-xs text-white/80">
                    {folder}
                  </div>
                  <div className="w-32 h-1.5 bg-white/5 rounded-full overflow-hidden">
                    <div className="h-full bg-accent" style={{ width: `${pct}%` }} />
                  </div>
                  <div className="text-xs text-white/50 tabular-nums w-12 text-right">
                    {count}
                  </div>
                </div>
              );
            })}
            {moreFolders > 0 && (
              <div className="text-xs text-white/40 pt-2">
                ... and {moreFolders} more folders
              </div>
            )}
          </div>
        </div>

        {/* Tag backup notice */}
        {result.backupPath && (
          <div className="panel-pad bg-accent-green/5 border-accent-green/30 text-sm">
            <div className="flex items-start gap-2">
              <CheckCircle2 className="w-4 h-4 text-accent-green flex-none mt-0.5" />
              <div>
                <div className="text-accent-green">Tag backup saved</div>
                <div className="text-xs text-white/60 mt-1 font-mono break-all">
                  {result.backupPath}
                </div>
                <div className="text-xs text-white/50 mt-1">
                  If anything looks wrong, you can restore tags from this file in the Tags tab.
                </div>
              </div>
            </div>
          </div>
        )}

        {/* Errors (collapsible) */}
        {result.errors.length > 0 && (
          <details className="panel-pad bg-accent-yellow/5 border-accent-yellow/30">
            <summary className="cursor-pointer text-sm font-medium text-accent-yellow flex items-center gap-2">
              <AlertCircle className="w-4 h-4" />
              {result.errors.length} files couldn't be moved
            </summary>
            <ul className="mt-3 space-y-1 max-h-64 overflow-auto text-xs font-mono text-white/60">
              {result.errors.slice(0, 100).map((err, i) => (
                <li key={i} className="break-all">{err}</li>
              ))}
              {result.errors.length > 100 && (
                <li className="text-white/40">... and {result.errors.length - 100} more</li>
              )}
            </ul>
          </details>
        )}

        {/* Undo result — which files couldn't be moved back. Only shown after a
            partial undo; a clean undo leaves it hidden. */}
        {undoResult && (undoResult.errorMessages.length > 0 || undoResult.skipped > 0) && (
          <details className="panel-pad bg-accent-yellow/5 border-accent-yellow/30" open>
            <summary className="cursor-pointer text-sm font-medium text-accent-yellow flex items-center gap-2 select-none">
              <AlertCircle className="w-4 h-4 flex-none" />
              Undo left{" "}
              {undoResult.skipped + undoResult.errorMessages.length} file
              {undoResult.skipped + undoResult.errorMessages.length === 1 ? "" : "s"} in place
            </summary>
            <div className="text-xs text-white/60 mt-2">
              Moved {undoResult.reverted} back
              {undoResult.skipped > 0 && `, skipped ${undoResult.skipped}`}
              {undoResult.errorMessages.length > 0 &&
                `, ${undoResult.errorMessages.length} error${
                  undoResult.errorMessages.length === 1 ? "" : "s"
                }`}
              . Skipped files were left where they are because the original path
              was occupied or the file was already moved.
            </div>
            {undoResult.errorMessages.length > 0 && (
              <ul className="mt-2 space-y-1 max-h-56 overflow-auto text-[11px] font-mono text-white/60 bg-black/20 rounded-sm p-2">
                {undoResult.errorMessages.slice(0, 100).map((m, i) => (
                  <li key={i} className="break-all">{m}</li>
                ))}
                {undoResult.errorMessages.length > 100 && (
                  <li className="text-white/40 italic">
                    …and {undoResult.errorMessages.length - 100} more
                  </li>
                )}
              </ul>
            )}
          </details>
        )}

        {/* Folders this organize emptied. Re-filing a sorted library moves the
            last track out of a genre folder and leaves the folder behind. We
            never delete one as part of the organize — offer it, with the list
            visible, and let the user decide. Hidden once undone: undo puts the
            files back, so the folders aren't empty any more. */}
        {result.emptiedDirs.length > 0 && !undone && !pruneResult && (
          <div className="panel-pad space-y-2">
            <div className="text-sm text-white">
              {result.emptiedDirs.length} folder
              {result.emptiedDirs.length === 1 ? " is" : "s are"} now empty
            </div>
            <p className="text-xs text-white/50">
              Every track moved out of{" "}
              {result.emptiedDirs.length === 1 ? "this folder" : "these folders"}. Removing
              them is optional and only removes the folders themselves — never a file.
            </p>
            <details className="text-xs">
              <summary className="cursor-pointer text-white/60 hover:text-white">
                Show folders
              </summary>
              <ul className="mt-2 space-y-0.5 font-mono text-white/50 max-h-40 overflow-auto">
                {result.emptiedDirs.map((d) => (
                  <li key={d} className="break-all">{d}</li>
                ))}
              </ul>
            </details>
            <button
              className="btn-ghost"
              onClick={() => setShowPruneConfirm(true)}
              disabled={pruning}
            >
              {pruning ? <Loader2 className="w-4 h-4 animate-spin" /> : <FolderTree className="w-4 h-4" />}
              Remove empty folders
            </button>
          </div>
        )}

        {pruneResult && (
          <div className="panel-pad space-y-2">
            <div className="text-sm text-white">
              Removed {pruneResult.removed.length} empty folder
              {pruneResult.removed.length === 1 ? "" : "s"}
            </div>
            {(pruneResult.skipped.length > 0 || pruneResult.errors.length > 0) && (
              <details className="text-xs" open>
                <summary className="cursor-pointer text-accent-yellow">
                  {pruneResult.skipped.length + pruneResult.errors.length} kept
                </summary>
                <ul className="mt-2 space-y-0.5 text-white/60 max-h-40 overflow-auto">
                  {pruneResult.skipped.map((s) => (
                    <li key={s.path} className="break-all">
                      <span className="font-mono">{s.path}</span> — {s.reason}
                    </li>
                  ))}
                  {pruneResult.errors.map((e) => (
                    <li key={e} className="break-all text-accent-yellow">{e}</li>
                  ))}
                </ul>
              </details>
            )}
          </div>
        )}

        <ConfirmModal
          open={showPruneConfirm}
          variant="danger"
          destructive
          title="Remove empty folders?"
          message={
            `${result.emptiedDirs.length} folder${result.emptiedDirs.length === 1 ? "" : "s"} ` +
            "will be removed. Only the folders go — no files are deleted, and any folder " +
            "that isn't actually empty is left alone. This is not covered by Undo."
          }
          confirmLabel="Remove folders"
          onConfirm={handlePrune}
          onCancel={() => setShowPruneConfirm(false)}
        />

        {/* Actions */}
        <div className="flex items-center gap-2 pt-4">
          {result.journalPath && result.moved > 0 && (
            <button
              className="btn-ghost text-accent-yellow"
              onClick={handleUndo}
              disabled={undoing || undone}
              title="Move every file back to where it was before this organize"
            >
              {undoing ? (
                <Loader2 className="w-4 h-4 animate-spin" />
              ) : (
                <Undo2 className="w-4 h-4" />
              )}
              {undone ? "Undone" : "Undo this organize"}
            </button>
          )}
          <div className="flex-1" />
          <button className="btn-ghost" onClick={onAnother}>
            <RotateCcw className="w-4 h-4" />
            Organize another folder
          </button>
          <button className="btn-primary" onClick={onViewLibrary}>
            <Eye className="w-4 h-4" />
            View library
          </button>
        </div>
      </div>
    </div>
  );
}

